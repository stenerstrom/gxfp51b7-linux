/* Original gf_set_config: category 9/subcommand 0, checksum enabled.
 * A single fixed 256-byte payload only; no caller-provided register data.
 */
static inline unsigned int chicago_config_frame(unsigned char *p, unsigned int capacity)
{
	unsigned int i, sum16 = 0xa5a5;
	unsigned char sum8 = 0;
	if (capacity < 264) return 0;
	for (i = 0; i < 256; i += 2)
		sum16 += chicago_default_config[i] | ((unsigned int)chicago_default_config[i + 1] << 8);
	if (sum16 & 0xffff) return 0;
	p[0] = 0xa0; p[1] = 4; p[2] = 1; p[3] = 0xa5;
	p[4] = 0x90; p[5] = 1; p[6] = 1;
	for (i = 0; i < 256; i++) p[i + 7] = chicago_default_config[i];
	for (i = 4; i < 263; i++) sum8 += p[i];
	p[263] = (unsigned char)(0xaa - sum8);
	return 264;
}
